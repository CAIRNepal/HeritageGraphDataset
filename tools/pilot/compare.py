#!/usr/bin/env python3
"""One comparison table for the pilot districts, from each district's summary.json (written by match.py).

Usage:  python3 tools/pilot/compare.py   ->  docs/pilot/COMPARISON.md
"""
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from districts import DISTRICTS, PILOT  # noqa: E402


def main():
    S = {k: json.load(open(os.path.join(PILOT, k, "summary.json"), encoding="utf-8"))
         for k in DISTRICTS if os.path.exists(os.path.join(PILOT, k, "summary.json"))}
    cols = list(S)
    head = "| | " + " | ".join(f"{S[k]['district']} ({DISTRICTS[k]['province']})" for k in cols) + " |"
    sep = "|---|" + "---:|" * len(cols)

    def row(label, f):
        return f"| {label} | " + " | ".join(f(S[k]) for k in cols) + " |"

    n = lambda v: f"{v:,}"  # noqa: E731
    L = ["# Pilot: DANAM, OpenStreetMap and Wikidata in three districts", "",
         "Generated by `tools/pilot/compare.py` from each district's `summary.json` (`tools/pilot/match.py`). Same OSM "
         "tags, Wikidata query and matching rules in every district; nothing is merged. Likely = less than 50 m apart "
         "and name similarity ≥ 0.7 with no conflict in the kind of building, or already linked by a source. Likely "
         "matches are not verified: the candidate files are for manual review.", "",
         head, sep,
         row("OSM boundary relation", lambda s: f"[{s['rel']}](https://www.openstreetmap.org/relation/{s['rel']})"),
         row("Wikidata item", lambda s: f"[{s['qid']}](https://www.wikidata.org/wiki/{s['qid']})"),
         row("OSM data as of", lambda s: s["osm_base"][:10]),
         "| **Counts** |" + " |" * len(cols),
         row("DANAM monuments (by coordinates)", lambda s: n(s["counts"]["danam"])),
         row("OSM features", lambda s: n(s["counts"]["osm"])),
         row("&nbsp;&nbsp;places of worship / historic=*", lambda s: f"{n(s['osm_place_of_worship'])} / {n(s['osm_historic'])}"),
         row("&nbsp;&nbsp;without a historic/heritage tag", lambda s: n(s["osm_no_heritage_tag"])),
         row("&nbsp;&nbsp;**look like recent buildings**", lambda s: n(s["osm_recent"])),
         row("Wikidata items", lambda s: n(s["counts"]["wikidata"])),
         "| **Likely overlaps (pairs)** |" + " |" * len(cols),
         row("DANAM – OSM", lambda s: n(s["pairs"]["danam-osm"]["likely"])),
         row("DANAM – Wikidata", lambda s: n(s["pairs"]["danam-wikidata"]["likely"])),
         row("OSM – Wikidata", lambda s: f"{n(s['pairs']['osm-wikidata']['likely'])} ({s['pairs']['osm-wikidata']['linked']} linked)"),
         "| **Items with a likely match** |" + " |" * len(cols),
         row("DANAM monuments with an OSM match", lambda s: n(s["with_likely_match"]["danam"]["osm"])),
         row("DANAM monuments with a Wikidata match", lambda s: n(s["with_likely_match"]["danam"]["wikidata"])),
         row("Wikidata items with an OSM match", lambda s: n(s["with_likely_match"]["wikidata"]["osm"])),
         "| **Unique to one source** (no likely match in either other) |" + " |" * len(cols),
         row("DANAM", lambda s: n(s["unique"]["danam"])),
         row("OSM (all / named)", lambda s: f"{n(s['unique']['osm'])} / {n(s['unique_named_osm'])}"),
         row("Wikidata", lambda s: n(s["unique"]["wikidata"])),
         ""]
    L += ["## Recent-looking OSM features", "",
          "Heuristic, applied only to features without a `historic=*` or `heritage=*` tag: religion Christian, a name "
          "with words such as church, fellowship, satsang, ashram, school, hall or bhawan, or a `start_date` from 1950 "
          "on. Features without these signals are not necessarily old: most OSM places of worship carry no date.", ""]
    for k in cols:
        s = S[k]
        L += [f"**{s['district']}**: {s['osm_recent']} of {s['counts']['osm']} OSM features (signals: "
              + (", ".join(f"{a} {b}" for a, b in s["osm_recent_signals"].items()) or "none") + "). Examples: "
              + ("; ".join(s["osm_recent_examples"][:5]) or "none") + ".", ""]
    L += ["## Notes", "",
          "- **DANAM covers neither Chitwan nor Kanchanpur.** None of its monuments has coordinates in either district or "
          "names either as its district; its westernmost records (33) are in the neighbouring hill districts Dadeldhura "
          "(Ajaymeru, Amargadhi) and Baitadi (Dasharathchand). In these two districts only OSM and Wikidata can be compared.",
          "- **Wikidata is sparse everywhere:** 11 items in Lalitpur, 5 in Chitwan, none in Kanchanpur for the classes "
          "queried (temple, stupa, monument, heritage site, or any heritage designation).",
          "- **OSM is mostly current places of worship:** outside Lalitpur, fewer than 5 % of OSM features carry a "
          "`historic=*` tag.",
          "- OSM tagging errors seen: in Lalitpur, two Newar monasteries named *bahī* are tagged `religion=bahai`.", ""]
    L += ["Details, examples and licences per district: " + ", ".join(f"[{S[k]['district']}]({k}/REPORT.md)" for k in cols)
          + ". Licences: OpenStreetMap ODbL 1.0 (© OpenStreetMap contributors); Wikidata CC0 1.0; DANAM not yet settled.", ""]
    open(os.path.join(PILOT, "COMPARISON.md"), "w", encoding="utf-8").write("\n".join(L) + "\n")
    print("\n".join(L[:30]))


if __name__ == "__main__":
    main()
